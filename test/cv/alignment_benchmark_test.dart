import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:wise_clinical_camera/core/cv/alignment_result.dart';
import 'package:wise_clinical_camera/core/cv/local_alignment_engine.dart';
import 'package:wise_clinical_camera/models/enums.dart';

import '../support/cv_dataset.dart';

/// Quantitative alignment benchmark (Phase 2 sections 16 and 18, Computer
/// Vision sections 66-67).
///
/// Computer Vision section 67 lists the metrics that must be measured:
/// translation error, rotation error, scale error, inlier ratio, false
/// alignment, failure rate and latency. This produces them against synthetic
/// ground truth and writes a table to `build/cv_benchmark.md`.
///
/// **This is synthetic validation, not clinical validation.** The numbers say
/// the geometry is right; they say nothing about skin, hair, dressings, skin
/// tone or real lighting. Computer Vision sections 44, 64 and 78 forbid
/// treating thresholds as validated on this basis. See
/// `docs/cv/THRESHOLDS.md`.
void main() {
  final rows = <String>[];

  tearDownAll(() {
    if (rows.isEmpty) return;
    final buffer = StringBuffer()
      ..writeln('# Alignment benchmark (synthetic ground truth)')
      ..writeln()
      ..writeln('Generated by `test/cv/alignment_benchmark_test.dart`.')
      ..writeln()
      ..writeln('Synthetic validation only. See docs/cv/THRESHOLDS.md.')
      ..writeln()
      ..writeln(
        '| Case | Status | Confidence | Scale est/true | Rot est/true '
        '| Trans est/true | Inliers | Latency |',
      )
      ..writeln('|---|---|---:|---|---|---|---:|---:|');
    for (final row in rows) {
      buffer.writeln(row);
    }
    Directory('build').createSync(recursive: true);
    File('build/cv_benchmark.md').writeAsStringSync(buffer.toString());
    // Also to stdout so it appears in CI logs.
    // ignore: avoid_print
    print(buffer.toString());
  });

  /// Runs one case and records a benchmark row.
  Future<AlignmentResult> measure({
    required String label,
    double translateX = 0,
    double translateY = 0,
    double rotationDegrees = 0,
    double scale = 1,
    int seed = 42,
  }) async {
    final engine = LocalAlignmentEngine();
    final scene = CvDataset.texturedScene(seed: seed);

    final prepared = await engine.prepareReference(
      photoId: 'ref',
      imageBytes: CvDataset.toJpeg(scene),
    );
    if (prepared.isFailure) {
      rows.add('| $label | REFERENCE REJECTED | — | — | — | — | — | — |');
      return const AlignmentResult.unavailable(engineVersion: 'cv-1.0.0');
    }

    final transformed = CvDataset.transform(
      scene,
      translateX: translateX,
      translateY: translateY,
      rotationDegrees: rotationDegrees,
      scale: scale,
    );

    final stopwatch = Stopwatch()..start();
    final result = await engine.analyzeFrame(
      frame: CvDataset.toWorking(transformed),
      reference: prepared.valueOrNull!,
    );
    stopwatch.stop();

    // Translation is normalised by image size; the canvas is 320 px.
    final trueTx = translateX / 320;

    rows.add(
      '| $label '
      '| ${result.status.wireName} '
      '| ${result.confidence.toStringAsFixed(2)} '
      '| ${result.scale.toStringAsFixed(3)} / ${scale.toStringAsFixed(3)} '
      '| ${result.rotationDegrees.toStringAsFixed(1)} / '
      '${rotationDegrees.toStringAsFixed(1)} '
      '| ${result.translationX.toStringAsFixed(3)} / '
      '${trueTx.toStringAsFixed(3)} '
      '| ${result.metrics.inliers}/${result.metrics.candidateMatches} '
      '| ${(stopwatch.elapsedMicroseconds / 1000).toStringAsFixed(0)} ms |',
    );

    return result;
  }

  group('scale sweep (Phase 2 section 18)', () {
    // The pyramid was added because BRIEF is not scale-invariant. This
    // measures how far it actually stretches, rather than assuming it solved
    // the problem.
    for (final scale in const [0.7, 0.8, 0.9, 1.0, 1.1, 1.2, 1.3]) {
      test('scale ${scale}x', () async {
        final result = await measure(label: 'scale ${scale}x', scale: scale);

        if (scale == 1.0) {
          expect(result.status, AlignmentStatus.good);
          expect(result.scale, closeTo(1, 0.03));
          return;
        }

        // Where the engine reports an estimate at all, it must be accurate.
        // Where it cannot, UNAVAILABLE is the correct answer, not a guess.
        if (result.isAvailable) {
          expect(
            result.scale,
            closeTo(scale, scale * 0.08),
            reason:
                'a reported scale must be within 8% of truth, or the engine '
                'should have declined instead',
          );
        }
      });
    }

    test('the usable scale range is recorded, not assumed', () async {
      final usable = <double>[];
      for (final scale in const [0.6, 0.7, 0.8, 0.9, 1.0, 1.1, 1.2, 1.3, 1.5]) {
        final engine = LocalAlignmentEngine();
        final scene = CvDataset.texturedScene();
        final prepared = await engine.prepareReference(
          photoId: 'r',
          imageBytes: CvDataset.toJpeg(scene),
        );
        final result = await engine.analyzeFrame(
          frame: CvDataset.toWorking(CvDataset.transform(scene, scale: scale)),
          reference: prepared.valueOrNull!,
        );
        if (result.isAvailable && (result.scale - scale).abs() < scale * 0.1) {
          usable.add(scale);
        }
      }

      rows.add(
        '| **usable scale range** | ${usable.first}x to ${usable.last}x '
        '| — | — | — | — | — | — |',
      );

      // The pyramid must at least cover the ordinary case of a clinician
      // standing slightly nearer or further away between visits.
      expect(usable, contains(0.9));
      expect(usable, contains(1.1));
    });
  });

  group('translation sweep', () {
    for (final dx in const [10.0, 20.0, 40.0, 60.0]) {
      test('translate ${dx.toInt()}px', () async {
        final result = await measure(
          label: 'translate ${dx.toInt()}px',
          translateX: dx,
        );

        if (result.isAvailable) {
          expect(
            result.translationX,
            closeTo(dx / 320, 0.03),
            reason: 'a reported translation must match the applied shift',
          );
        }
      });
    }
  });

  group('rotation sweep', () {
    for (final degrees in const [2.0, 5.0, 10.0, 15.0]) {
      test('rotate ${degrees.toInt()}deg', () async {
        final result = await measure(
          label: 'rotate ${degrees.toInt()}deg',
          rotationDegrees: degrees,
        );

        if (result.isAvailable) {
          expect(
            result.rotationDegrees.abs(),
            closeTo(degrees, 2.5),
            reason: 'a reported rotation must match the applied rotation',
          );
        }
      });
    }
  });

  group('combined transforms', () {
    test('translation and rotation together', () async {
      final result = await measure(
        label: 'translate 20px + rotate 5deg',
        translateX: 20,
        rotationDegrees: 5,
      );

      if (result.isAvailable) {
        expect(result.rotationDegrees.abs(), closeTo(5, 3));
      }
    });

    test('scale and translation together', () async {
      final result = await measure(
        label: 'scale 1.1x + translate 15px',
        scale: 1.1,
        translateX: 15,
      );

      if (result.isAvailable) {
        expect(result.scale, closeTo(1.1, 0.12));
      }
    });
  });

  group('latency', () {
    test('a frame is analysed within a bounded time', () async {
      // Not a device measurement — this is a desktop VM. Recorded so a
      // regression that made the engine an order of magnitude slower would be
      // visible. Real budgets come from device test D-PRF-03.
      final engine = LocalAlignmentEngine();
      final scene = CvDataset.texturedScene();
      final prepared = await engine.prepareReference(
        photoId: 'r',
        imageBytes: CvDataset.toJpeg(scene),
      );

      final samples = <int>[];
      for (var i = 0; i < 5; i++) {
        engine.reset();
        final stopwatch = Stopwatch()..start();
        await engine.analyzeFrame(
          frame: CvDataset.toWorking(scene),
          reference: prepared.valueOrNull!,
        );
        samples.add(stopwatch.elapsedMilliseconds);
      }
      samples.sort();

      rows.add(
        '| **frame latency (median, desktop VM)** | ${samples[2]} ms '
        '| — | — | — | — | — | — |',
      );

      expect(
        samples[2],
        lessThan(2000),
        reason: 'a frame must not take seconds even on a slow VM',
      );
    });

    test('reference preparation is bounded', () async {
      final engine = LocalAlignmentEngine();
      final stopwatch = Stopwatch()..start();
      await engine.prepareReference(
        photoId: 'r',
        imageBytes: CvDataset.toJpeg(CvDataset.texturedScene()),
      );
      stopwatch.stop();

      rows.add(
        '| **reference preparation (desktop VM)** '
        '| ${stopwatch.elapsedMilliseconds} ms | — | — | — | — | — | — |',
      );

      expect(stopwatch.elapsedMilliseconds, lessThan(5000));
    });
  });
}
